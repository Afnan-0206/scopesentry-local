import { StoredProject } from '../types.js';
import { ScopeAssessment } from '@scopesentry/shared';
import { DEMO_PROJECTS } from '../fixtures/demo-projects.js';

const STORAGE_KEY = 'scopesentry_projects_v1';
const DEMO_STORAGE_KEY = 'scopesentry_demo_projects_v1';

export class StorageService {
  public static getProjects(isDemoMode: boolean): StoredProject[] {
    const key = isDemoMode ? DEMO_STORAGE_KEY : STORAGE_KEY;
    try {
      const data = localStorage.getItem(key);
      if (!data) {
        if (isDemoMode) {
          // Initialize demo projects
          localStorage.setItem(DEMO_STORAGE_KEY, JSON.stringify(DEMO_PROJECTS));
          return DEMO_PROJECTS;
        }
        return [];
      }
      return JSON.parse(data);
    } catch (e) {
      console.error('Failed to read from localStorage:', e);
      return isDemoMode ? DEMO_PROJECTS : [];
    }
  }

  public static getProject(id: string, isDemoMode: boolean): StoredProject | undefined {
    const list = this.getProjects(isDemoMode);
    return list.find((p) => p.id === id);
  }

  public static saveProject(project: StoredProject, isDemoMode: boolean): void {
    const key = isDemoMode ? DEMO_STORAGE_KEY : STORAGE_KEY;
    const list = this.getProjects(isDemoMode);
    const index = list.findIndex((p) => p.id === project.id);
    if (index >= 0) {
      list[index] = { ...project, updatedAt: new Date().toISOString() };
    } else {
      list.unshift(project);
    }
    localStorage.setItem(key, JSON.stringify(list));
  }

  public static deleteProject(id: string, isDemoMode: boolean): void {
    const key = isDemoMode ? DEMO_STORAGE_KEY : STORAGE_KEY;
    const list = this.getProjects(isDemoMode).filter((p) => p.id !== id);
    localStorage.setItem(key, JSON.stringify(list));
  }

  public static addAssessment(projectId: string, assessment: ScopeAssessment, isDemoMode: boolean): void {
    const project = this.getProject(projectId, isDemoMode);
    if (project) {
      project.assessments = [assessment, ...(project.assessments || [])];
      this.saveProject(project, isDemoMode);
    }
  }

  public static clearAllData(): void {
    localStorage.removeItem(STORAGE_KEY);
    localStorage.removeItem(DEMO_STORAGE_KEY);
  }

  public static exportProjectJson(project: StoredProject): string {
    return JSON.stringify(project, null, 2);
  }

  public static exportAssessmentMarkdown(project: StoredProject, assessment: ScopeAssessment): string {
    const verifiedQuotes = assessment.supportingQuotations.filter((q) => q.isVerified);
    const unverifiedQuotes = assessment.supportingQuotations.filter((q) => !q.isVerified);

    return `# ScopeSentry Assessment Report

**Project:** ${project.projectName}  
**Client:** ${project.clientLabel || 'N/A'}  
**Date:** ${new Date(assessment.evaluatedAt).toLocaleString()}  
**Primary Status:** **${assessment.primaryStatus}**  

---

## Decision Summary
${assessment.shortSummary}

## Requested Changes Identified
${assessment.requestedChangesIdentified.length > 0 ? assessment.requestedChangesIdentified.map((c) => `- ${c}`).join('\n') : '- None recorded'}

## Relevant Original Scope Items
${assessment.relevantOriginalScopeItems.length > 0 ? assessment.relevantOriginalScopeItems.map((s) => `- ${s}`).join('\n') : '- None recorded'}

## Verified Evidence from Original Agreement
${
  verifiedQuotes.length > 0
    ? verifiedQuotes
        .map(
          (q) => `> "${q.quote}"\n\n*Why it matters:* ${q.whyItMatters || 'Supports scope boundary.'}`
        )
        .join('\n\n')
    : '_No verified quotations confirmed in original agreement text._'
}

${
  unverifiedQuotes.length > 0
    ? `### ⚠️ Unverified Citations (Flagged by Deterministic Verifier)\n` +
      unverifiedQuotes
        .map((q) => `- "${q.quote}" — ${q.warning || 'Could not be verified in agreement source text.'}`)
        .join('\n')
    : ''
}

${
  assessment.evidenceValidationWarnings.length > 0
    ? `### Validation Warnings\n` +
      assessment.evidenceValidationWarnings.map((w) => `- ${w}`).join('\n')
    : ''
}

## Missing or Ambiguous Information
${
  assessment.missingOrAmbiguousInfo.length > 0
    ? assessment.missingOrAmbiguousInfo.map((m) => `- ${m}`).join('\n')
    : '- None identified'
}

## Recommended Next Step
${assessment.suggestedNextStep}

---

## Suggested Professional Reply Draft
\`\`\`
${assessment.draftReply}
\`\`\`

---
*Generated by ScopeSentry Local. This tool assists with freelance scope management and does not constitute formal legal advice.*
`;
  }
}
