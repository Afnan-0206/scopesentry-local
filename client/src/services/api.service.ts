import {
  AnalyzeAgreementInput,
  AnalyzeAgreementResponse,
  CompareRequestInput,
  ScopeAssessment,
  DraftReplyInput,
  DraftReplyResponse
} from '@scopesentry/shared';

export interface BackendHealth {
  status: string;
  service: string;
  privacy: {
    boundHost: string;
    isLoopback: boolean;
    externalThirdPartyAiApis: boolean;
    telemetry: boolean;
  };
  ollama: {
    isRunning: boolean;
    version?: string;
    configuredModel: string;
    isConfiguredModelInstalled: boolean;
    availableModels: string[];
    error?: string;
  };
}

export class ApiService {
  private static baseUrl = ''; // Proxied via Vite to http://127.0.0.1:3001

  public static async getHealth(): Promise<BackendHealth> {
    const res = await fetch(`${this.baseUrl}/api/health`);
    if (!res.ok) {
      throw new Error(`Backend health check failed with status ${res.status}`);
    }
    return res.json();
  }

  public static async getModels(): Promise<{ models: string[]; configured: string; isConfiguredAvailable: boolean }> {
    const res = await fetch(`${this.baseUrl}/api/models`);
    if (!res.ok) {
      throw new Error(`Failed to fetch models from local backend`);
    }
    return res.json();
  }

  public static async analyzeAgreement(
    input: AnalyzeAgreementInput,
    isDemoMode: boolean
  ): Promise<AnalyzeAgreementResponse> {
    if (isDemoMode) {
      // Deterministic demo extraction simulation
      await new Promise((r) => setTimeout(r, 600));
      return {
        extractedScope: {
          deliverables: [
            {
              id: 'demo_d1',
              text: 'Project deliverables as agreed in agreement text',
              verbatimQuote: input.originalAgreementText.slice(0, 80),
              isVerified: true,
            },
          ],
          explicitInclusions: [],
          explicitExclusions: [],
          constraints: [],
          revisionPolicy: null,
          milestonesAndDeadlines: [],
          assumptions: ['Standard delivery assumptions applied in demo fixture'],
          ambiguousOrConflictingClauses: [],
          evidenceExcerpts: [],
        },
        verifiedQuotesCount: 1,
        unverifiedQuotesCount: 0,
        warnings: ['Prerecorded fixture demo mode active.'],
      };
    }

    const res = await fetch(`${this.baseUrl}/api/agreements/analyze`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(input),
    });

    if (!res.ok) {
      const errorData = await res.json().catch(() => ({}));
      throw new Error(errorData.error || `Agreement analysis failed (HTTP ${res.status})`);
    }

    return res.json();
  }

  public static async compareRequest(
    input: CompareRequestInput,
    isDemoMode: boolean
  ): Promise<ScopeAssessment> {
    if (isDemoMode) {
      await new Promise((r) => setTimeout(r, 700));
      const hasExcludedKeyword = /auth|login|stripe|portal|payment|database/i.test(input.newClientRequest);
      const status = hasExcludedKeyword ? 'POTENTIAL SCOPE CHANGE' : 'INCLUDED';

      return {
        id: `demo_assess_${Date.now()}`,
        projectId: input.projectId,
        primaryStatus: status,
        shortSummary:
          status === 'POTENTIAL SCOPE CHANGE'
            ? 'The requested feature appears to exceed the deliverables agreed in the statement of work.'
            : 'The requested update is directly aligned with agreed deliverables.',
        requestedChangesIdentified: [input.newClientRequest.slice(0, 60)],
        relevantOriginalScopeItems: input.approvedScope.deliverables.map((d) => d.text).slice(0, 2),
        supportingQuotations: [
          {
            id: 'demo_q1',
            quote: input.originalAgreementText.slice(0, 70),
            whyItMatters: 'Demonstrates agreement scope boundary in demo mode.',
            isVerified: true,
          },
        ],
        missingOrAmbiguousInfo: [],
        suggestedNextStep:
          status === 'POTENTIAL SCOPE CHANGE'
            ? 'Discuss additional timeline and budget before commencing work.'
            : 'Proceed with delivery as scheduled.',
        draftReply: `Hi there,\n\nThanks for reaching out! Regarding your request:\n• ${input.newClientRequest}\n\n${
          status === 'POTENTIAL SCOPE CHANGE'
            ? 'This goes beyond our agreed deliverables. I would be happy to put together a separate estimate for this additional scope.'
            : 'This is included in our agreed deliverables. I will proceed with this update.'
        }\n\nBest regards,`,
        evidenceValidationWarnings: ['Demo fixture output (not generated by live Ollama model).'],
        evaluatedAt: new Date().toISOString(),
      };
    }

    const res = await fetch(`${this.baseUrl}/api/compare`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(input),
    });

    if (!res.ok) {
      const errorData = await res.json().catch(() => ({}));
      throw new Error(errorData.error || `Scope comparison failed (HTTP ${res.status})`);
    }

    return res.json();
  }

  public static async draftReply(
    input: DraftReplyInput,
    isDemoMode: boolean
  ): Promise<DraftReplyResponse> {
    if (isDemoMode) {
      const fee = input.proposedFee ? `\nEstimated investment: ${input.proposedFee}` : '';
      const timeline = input.proposedTimeline ? `\nEstimated timeline adjustment: ${input.proposedTimeline}` : '';
      return {
        draftReply: `Hi there,\n\nThank you for reaching out!\n\nRegarding your request:\n${input.assessment.requestedChangesIdentified.map((c) => `• ${c}`).join('\n')}\n\nThis appears to exceed our agreed deliverables.${fee}${timeline}\n\nPlease let me know how you would like to proceed!\n\nBest regards,`,
        includesUserFee: Boolean(input.proposedFee),
        includesUserTimeline: Boolean(input.proposedTimeline),
        warnings: [],
      };
    }

    const res = await fetch(`${this.baseUrl}/api/replies/draft`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(input),
    });

    if (!res.ok) {
      const errorData = await res.json().catch(() => ({}));
      throw new Error(errorData.error || `Reply generation failed (HTTP ${res.status})`);
    }

    return res.json();
  }
}
